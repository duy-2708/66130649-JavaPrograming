
public class HocSinh {
private String Ten ;
private int Tuoi ;
public HocSinh() {
	this.Ten = Ten ;
	this.Tuoi = Tuoi ;
}
public String getTen() {
	return Ten;
}
public void setTen(String ten) {
	Ten = ten;
}
public int getTuoi() {
	return Tuoi;
}
public void setTuoi(int tuoi) {
	Tuoi = tuoi;
}
public int TuoiThat() {
	return 2026-Tuoi ;
}
}
